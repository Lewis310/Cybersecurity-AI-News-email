"""
Weekly AI Cybersecurity Report Generator
Calls Gemini to generate a report, then emails it via SMTP.
"""

import os
import smtplib
import datetime
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
import google.generativeai as genai

# ── Gemini setup ─────────────────────────────────────────────────────────────

genai.configure(api_key=os.environ["GEMINI_API_KEY"])
model = genai.GenerativeModel("gemini-1.5-flash")

# ── Prompt ────────────────────────────────────────────────────────────────────

today = datetime.date.today().strftime("%B %d, %Y")

PROMPT = f"""
You are a senior cybersecurity analyst. Today is {today}.

Write a professional weekly cybersecurity briefing covering the past 7 days.
Structure it exactly as follows:

1. EXECUTIVE SUMMARY (2-3 sentences)

2. TOP THREATS & VULNERABILITIES (3-5 bullet points)
   - CVEs, zero-days, or major vulnerabilities disclosed this week
   - Include severity ratings where relevant

3. NOTABLE INCIDENTS & BREACHES (3-5 bullet points)
   - Confirmed breaches, ransomware attacks, or significant incidents

4. THREAT ACTOR ACTIVITY (2-3 bullet points)
   - APT groups, ransomware gangs, or nation-state activity

5. PATCHES & UPDATES TO APPLY (3-5 bullet points)
   - Critical patches from Microsoft, Apple, Cisco, etc.

6. RECOMMENDATIONS FOR DEFENDERS (3-4 actionable tips)

7. RESOURCES & FURTHER READING (2-3 links or reports to check)

Keep the tone professional but concise. Use plain language where possible.
Format clearly with headers and bullet points.
"""

# ── Generate report ───────────────────────────────────────────────────────────

print("Generating report with Gemini...")
response = model.generate_content(PROMPT)
report_text = response.text
print("Report generated successfully.")

# ── Build HTML email ──────────────────────────────────────────────────────────

def text_to_html(text: str) -> str:
    """Convert the plain-text report to a clean HTML email."""
    lines = text.split("\n")
    html_lines = []
    for line in lines:
        stripped = line.strip()
        if not stripped:
            html_lines.append("<br>")
        elif stripped[0].isdigit() and stripped[1] in ".":
            # Numbered section header
            html_lines.append(f"<h2 style='color:#1a1a2e;margin-top:24px;margin-bottom:8px;font-size:16px'>{stripped}</h2>")
        elif stripped.startswith("- ") or stripped.startswith("• "):
            html_lines.append(f"<li style='margin-bottom:6px'>{stripped[2:]}</li>")
        else:
            html_lines.append(f"<p style='margin:6px 0'>{stripped}</p>")

    body = "\n".join(html_lines)
    week_str = datetime.date.today().strftime("%B %d, %Y")

    return f"""
<!DOCTYPE html>
<html>
<head><meta charset="utf-8"></head>
<body style="font-family:Arial,sans-serif;max-width:700px;margin:0 auto;padding:24px;color:#333">
  <div style="background:#1a1a2e;color:#fff;padding:20px 24px;border-radius:8px 8px 0 0">
    <h1 style="margin:0;font-size:22px">🔐 Weekly Cybersecurity Report</h1>
    <p style="margin:4px 0 0;opacity:0.8;font-size:14px">Week of {week_str}</p>
  </div>
  <div style="border:1px solid #ddd;border-top:none;padding:24px;border-radius:0 0 8px 8px">
    {body}
  </div>
  <p style="font-size:12px;color:#999;margin-top:16px;text-align:center">
    Generated by Gemini AI · Delivered via GitHub Actions
  </p>
</body>
</html>
"""

html_body = text_to_html(report_text)

# ── Send email ────────────────────────────────────────────────────────────────

smtp_host = os.environ["SMTP_HOST"]
smtp_port = int(os.environ.get("SMTP_PORT", 587))
smtp_user = os.environ["SMTP_USER"]
smtp_pass = os.environ["SMTP_PASS"]
email_to  = os.environ["EMAIL_TO"]

week_str = datetime.date.today().strftime("%B %d, %Y")
subject  = f"🔐 Weekly Cybersecurity Report – {week_str}"

msg = MIMEMultipart("alternative")
msg["Subject"] = subject
msg["From"]    = smtp_user
msg["To"]      = email_to

msg.attach(MIMEText(report_text, "plain"))
msg.attach(MIMEText(html_body,   "html"))

print(f"Sending email to {email_to} via {smtp_host}:{smtp_port}...")
with smtplib.SMTP(smtp_host, smtp_port) as server:
    server.ehlo()
    server.starttls()
    server.login(smtp_user, smtp_pass)
    server.sendmail(smtp_user, email_to, msg.as_string())

print("Email sent successfully! ✓")
